struct PiStats {
  bool  valid;
  char  host[24];
  float cpu, memUsed, memTotal, diskUsed, diskTotal, temp;
};
PiStats g_pi = {false, "", 0, 0, 0, 0, 0, 0};

void fetchPiStats() {
  if (cfg.piHost[0] == '\0') { g_pi.valid = false; return; }
  WiFiClient client;                 // plain HTTP to the Pi agent (no TLS)
  HTTPClient http;
  String url = String("http://") + cfg.piHost + ":" + cfg.piPort + "/";
  if (!http.begin(client, url)) { g_pi.valid = false; return; }
  http.addHeader("User-Agent", "Glance/1.0");
  int code = http.GET();
  if (code != HTTP_CODE_OK) { http.end(); g_pi.valid = false; return; }
  String payload = http.getString();
  http.end();
  JsonDocument doc;
  if (deserializeJson(doc, payload)) { g_pi.valid = false; return; }
  strlcpy(g_pi.host, doc["host"] | "pi", sizeof(g_pi.host));
  g_pi.cpu       = doc["cpu"]        | 0.0f;
  g_pi.memUsed   = doc["mem_used"]   | 0.0f;
  g_pi.memTotal  = doc["mem_total"]  | 0.0f;
  g_pi.diskUsed  = doc["disk_used"]  | 0.0f;
  g_pi.diskTotal = doc["disk_total"] | 0.0f;
  g_pi.temp      = doc["temp"]       | 0.0f;
  g_pi.valid     = true;
}

