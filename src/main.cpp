bool isNightNow() {
  time_t now = time(nullptr);
  if (now <= 100000) return false;  // clock not synced
  struct tm tm;
  localtime_r(&now, &tm);
  int h = tm.tm_hour;
  if (cfg.nightStart == cfg.nightEnd) return false;
  if (cfg.nightStart < cfg.nightEnd) return h >= cfg.nightStart && h < cfg.nightEnd;
  return h >= cfg.nightStart || h < cfg.nightEnd;  // window wraps past midnight
}

// Seconds progress ring around the edge (updated once per second).
void drawSecondsRing(int sec) {
  const int cx = 120, cy = 112, r = 100, ir = 97;
  uint16_t track = tft.color565(30, 34, 44);
  uint16_t acc   = tft.color565(90, 150, 255);
  tft.drawArc(cx, cy, r, ir, 0, 360, track, COL_BG, false);
  if (sec == 0) return;
  // TFT_eSPI: 0deg = 6 o'clock, increasing clockwise -> 180deg = 12 o'clock.
  int e = 180 + (sec * 360) / 60;
  if (e <= 360) tft.drawArc(cx, cy, r, ir, 180, e, acc, COL_BG, false);
  else { tft.drawArc(cx, cy, r, ir, 180, 360, acc, COL_BG, false);
         tft.drawArc(cx, cy, r, ir, 0, e - 360, acc, COL_BG, false); }
}

