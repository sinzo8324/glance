// Draw a 1-bpp Korean label bitmap (MSB-first, row-padded to bytes) from PROGMEM.
void drawKRLabel(int x, int y, const KRLabel& L, uint16_t color) {
  uint16_t byteW = (L.w + 7) / 8;
  for (uint16_t j = 0; j < L.h; j++) {
    int runStart = -1;
    for (uint16_t i = 0; i <= L.w; i++) {
      bool on = i < L.w &&
          (pgm_read_byte(&L.data[j * byteW + i / 8]) & (0x80 >> (i & 7)));
      if (on && runStart < 0) runStart = i;
      if (!on && runStart >= 0) {
        tft.drawFastHLine(x + runStart, y + j, i - runStart, color);
        runStart = -1;
      }
    }
  }
}

// Blit a full-color RGB565 logo in one windowed transfer.
void drawLogo(int x, int y, const CoinLogo* L) {
  bool oldSwap = tft.getSwapBytes();
  tft.setSwapBytes(true);
  tft.pushImage(x, y, L->w, L->h, L->data);
  tft.setSwapBytes(oldSwap);
}

// Mini line chart of pts[0..n) inside the box (x0,y0,w,h), auto-scaled.
void drawSparkline(int x0, int y0, int w, int h, const float* pts, int n, uint16_t c) {
  if (n < 2) return;
  float mn = pts[0], mx = pts[0];
  for (int i = 1; i < n; i++) { if (pts[i] < mn) mn = pts[i]; if (pts[i] > mx) mx = pts[i]; }
  float range = mx - mn;
  if (range <= 0) range = 1;
  int pxPrev = 0, pyPrev = 0;
  for (int i = 0; i < n; i++) {
    int px = x0 + (w * i) / (n - 1);
    int py = y0 + h - (int)((pts[i] - mn) / range * h);
    if (i > 0) tft.drawLine(pxPrev, pyPrev, px, py, c);
    pxPrev = px; pyPrev = py;
  }
}

void drawRow(int y, const Ticker& t) {
  uint16_t chColor = (t.changePct >= 0) ? colUp() : colDown();

  int lx = 8;
  if (t.logo) {
    drawLogo(lx, y + 3, t.logo);
    lx += t.logo->w + 6;
  }
  if (t.kr) {
    drawKRLabel(lx, y + 2, *t.kr, colLabel());
  } else {
    tft.setTextDatum(TL_DATUM);
    tft.setTextColor(colLabel(), COL_BG);
    tft.drawString(t.label, lx, y + 1, 4);
  }

  if (!t.valid) {
    tft.setTextDatum(TR_DATUM);
    tft.setTextColor(COL_DIM, COL_BG);
    tft.drawString("--", 232, y + 2, 4);
    return;
  }

  tft.loadFont(PRICE_FONT);
  tft.setTextDatum(TR_DATUM);
  tft.setTextColor(COL_TEXT, COL_BG);
  tft.drawString(withCommas(t.price, t.decimals), 232, y - 8);
  tft.unloadFont();

  char pct[16];
  snprintf(pct, sizeof(pct), "%.2f%%", fabs(t.changePct));
  tft.setTextDatum(TR_DATUM);
  tft.setTextColor(chColor, COL_BG);
  tft.drawString(pct, 232, y + 22, 2);
  int pw = tft.textWidth(pct, 2);
  int tr = 232 - pw - 5, tl = tr - 7;
  int yt = y + 25, yb = y + 34;
  bool up = t.changePct >= 0;
  if (up) tft.fillTriangle(tl, yb, tr, yb, (tl + tr) / 2, yt, chColor);
  else    tft.fillTriangle(tl, yt, tr, yt, (tl + tr) / 2, yb, chColor);

  if (t.sparkN >= 2) drawSparkline(8, y + 29, 140, 9, t.spark, t.sparkN, chColor);
}

