void handleSave() {
  uint8_t previousMode = cfg.mode;
  if (httpServer.hasArg("br")) cfg.brightness  = constrain(httpServer.arg("br").toInt(), 0, 255);
  if (httpServer.hasArg("nb")) cfg.nightBright = constrain(httpServer.arg("nb").toInt(), 0, 255);
  if (httpServer.hasArg("ns")) cfg.nightStart  = constrain(httpServer.arg("ns").toInt(), 0, 23);
  if (httpServer.hasArg("nd")) cfg.nightEnd    = constrain(httpServer.arg("nd").toInt(), 0, 23);
  if (httpServer.hasArg("ps")) cfg.pageSec     = constrain(httpServer.arg("ps").toInt(), 2, 60);
  if (httpServer.hasArg("fs")) cfg.fetchSec    = constrain(httpServer.arg("fs").toInt(), 15, 600);
  if (httpServer.hasArg("md")) cfg.mode        = constrain(httpServer.arg("md").toInt(), 0, NUM_MODES - 1);
  if (httpServer.hasArg("pp")) cfg.piPort      = constrain(httpServer.arg("pp").toInt(), 1, 65535);
  if (httpServer.hasArg("ph")) strlcpy(cfg.piHost, httpServer.arg("ph").c_str(), sizeof(cfg.piHost));
  cfg.nightDim   = httpServer.hasArg("dm");    // checkboxes only post when ticked
  cfg.nightClock = httpServer.hasArg("nc");
  forceFullRedraw = previousMode != cfg.mode;
  if (previousMode != cfg.mode) autoClock = false;  // explicit mode change overrides auto-clock
  cfgSave();
  applyBrightness(isNightNow() ? cfg.nightBright : cfg.brightness);
  clockMode = false; lastClockMin = -1; lastPage = 0;
  lastFetch = 0;  // refetch in the (possibly new) mode right away
  httpServer.sendHeader("Location", "/");
  httpServer.send(303, "text/plain", "saved");
}

