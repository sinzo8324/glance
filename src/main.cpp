// Switch into a mode and force a clean redraw + refetch on the next loop.
void applyMode(uint8_t m) {
  cfg.mode = m % NUM_MODES;
  autoClock = false;           // an explicit choice overrides tonight's auto-clock
  forceFullRedraw = true;
  clockMode = false; lastClockMin = -1; lastSec = -1;
  lastPage = millis();
  lastFetch = 0;               // (re)fetch for the new mode right away
  renderCurrent();             // show the frame NOW; async fetch fills the data in
}

#if defined(ESP32)
enum TouchGesture { G_NONE, G_TAP, G_DOUBLE, G_LONG };

void calibrateTouch() {
  long acc = 0;
  for (int i = 0; i < 16; i++) { acc += touchRead(TOUCH_GPIO); delay(6); }
  touchBaseline = acc / 16;
  Serial.printf("touch baseline (GPIO%d) = %d\n", TOUCH_GPIO, touchBaseline);
}

// One-pad gesture recognizer. Returns at most one gesture per call. A single
// tap is reported only after the double-tap window lapses, so it can be told
// apart from a double tap; a long press fires while still held and suppresses
// the tap that would otherwise land on release.
// detectDouble=false (normal view): a tap fires immediately on release -- there's
// no double-tap action there, so waiting for one only adds lag and lets the 6s
// auto-page timer race in for a phantom second advance. =true (menu): defer to
// tell a single tap from a double.
TouchGesture pollTouch(bool detectDouble) {
  static bool     pressed = false;
  static uint32_t pressStart = 0;
  static bool     longFired = false;
  static bool     pendingTap = false;
  static uint32_t lastTapMs = 0;

  uint32_t now = millis();
  int v = touchRead(TOUCH_GPIO);
  // Schmitt trigger: engage at TOUCH_TRIG, release only after recovering to
  // TOUCH_REL, so a single wobbly touch can't chatter into multiple taps.
  float drop = touchBaseline > 0 ? (float)(touchBaseline - v) / touchBaseline : 0;
  bool down = pressed ? (drop > TOUCH_REL) : (drop > TOUCH_TRIG);
  TouchGesture g = G_NONE;

  if (down && !pressed) {                 // press edge
    pressed = true; pressStart = now; longFired = false;
  } else if (down && pressed) {           // held
    if (!longFired && now - pressStart >= LONGPRESS_MS) {
      longFired = true; pendingTap = false; g = G_LONG;
    }
  } else if (!down && pressed) {          // release edge
    pressed = false;
    if (!longFired) {                     // released before the long-press point => a tap
      if (!detectDouble)                              g = G_TAP;         // view: fire now
      else if (pendingTap && now - lastTapMs <= DOUBLETAP_MS) { pendingTap = false; g = G_DOUBLE; }
      else                                            { pendingTap = true; lastTapMs = now; }
    }
  }
  // menu only: a lone tap resolves once no second tap arrived in the window
  if (detectDouble && g == G_NONE && pendingTap && now - lastTapMs > DOUBLETAP_MS) {
    pendingTap = false; g = G_TAP;
  }
  return g;
}

void openModeMenu() {
  inMenu = true;
  menuSel = (cfg.mode < NUM_MODES) ? cfg.mode : 0;
  menuOpenedMs = millis();
  drawModeMenu();
}
void closeModeMenu() {                    // leave the menu without changing mode
  inMenu = false;
  applyMode(cfg.mode);                    // redraw the current mode cleanly
}

// Map a gesture to an action, in whichever context we're in.
void applyGesture(TouchGesture g) {
  if (g == G_NONE) return;
  if (!inMenu) {
    if (g == G_TAP) {                     // next page (market mode, and not while the clock is up)
      if (cfg.mode == 0 && !clockMode) { page = (page + 1) % NUM_PAGES; drawPage(false, true); lastPage = millis(); }
    } else if (g == G_LONG) {             // open the mode menu
      openModeMenu();
    }
    // G_DOUBLE: reserved / unused in normal view
  } else {
    menuOpenedMs = millis();              // any gesture resets the inactivity timer
    if (g == G_TAP)         { menuSel = (menuSel + 1) % NUM_MODES; drawModeMenu(); }
    else if (g == G_DOUBLE) { applyMode(menuSel); inMenu = false; }
    else if (g == G_LONG)   { closeModeMenu(); }
  }
}
#endif  // ESP32

void setup() {
  Serial.begin(115200);
  cfgLoad();
  tft.init();
  tft.setRotation(ROTATION);
  tft.invertDisplay(INVERT_COLORS);
  tft.fillScreen(COL_BG);

  // Backlight is ACTIVE-LOW: PWM duty is inverted, so higher duty = dimmer.
  pinMode(TFT_BL, OUTPUT);
#if !defined(ESP32)
  analogWriteRange(255);          // ESP32's analogWrite is 8-bit already
#endif
  applyBrightness(cfg.brightness);

  connectWiFi();
  startWebServer();
#if defined(ESP32)
  calibrateTouch();               // Pro: sample the idle touch level before use
#endif
  configTime(TZ_OFFSET_SEC, 0, "pool.ntp.org", "time.nist.gov");  // NTP for clock
  drawSplash("loading data...");   // the first fetch can take ~20 s
  fetchCurrent();
  lastFetch = millis();
  g_displayStartMs = millis();  // start the IP-visible window from here, not from boot
  renderCurrent();
  lastPage = millis();

#if defined(ESP32)
  // Hand all further fetches to core 0 so the UI (core 1) never blocks on I/O.
  // 16KB stack covers the TLS/JSON work; priority 1 keeps it below the UI.
  xTaskCreatePinnedToCore(fetchTask, "fetch", 16384, nullptr, 1, nullptr, 0);
#endif
}

void loop() {
  uint32_t now = millis();

  httpServer.handleClient();  // serve status page + OTA uploads

  // Non-blocking reconnect if WiFi drops (uses saved creds, no portal here).
  if (WiFi.status() != WL_CONNECTED) {
    WiFi.reconnect();
    delay(500);
    return;
  }

  // Touch button (Pro): drive page/mode navigation. On the Ultra there's no
  // pad, so inMenu never becomes true and this whole section is compiled out.
#if defined(ESP32)
  applyGesture(pollTouch(inMenu));   // view: tap fires immediately; menu: wait to detect double
  // Fresh millis() here: menuOpenedMs is set *during* applyGesture (after `now`
  // was captured at the top of loop), so `now - menuOpenedMs` would underflow
  // and fire the timeout the instant the menu opens.
  if (inMenu && millis() - menuOpenedMs > MENU_TIMEOUT_MS) closeModeMenu();
#endif
  if (inMenu) { delay(20); return; }   // menu is showing: pause fetch/render

  // Refresh `now`: a tap handled above set lastPage=millis() (later than the
  // `now` captured at the top of loop), so the page/fetch timers below would see
  // `now - lastPage` underflow and fire a phantom second page advance.
  now = millis();

  // Keep fetching in the background. Pi monitor uses its own fast interval
  // (local agent, no rate limit); market uses the configurable Refresh (s).
  uint32_t fetchInterval = (cfg.mode == 1) ? PIMON_INTERVAL_MS
                                           : (uint32_t)cfg.fetchSec * 1000UL;
#if defined(ESP32)
  // Kick the background fetch on interval; draw only once it reports fresh data.
  if (now - lastFetch >= fetchInterval && !g_fetching) { lastFetch = now; g_fetchReq = true; }
  if (g_fetchDone) {
    g_fetchDone = false;
    if (!clockMode) {
      if (cfg.mode == 0) drawPage(forceFullRedraw);
      else if (cfg.mode == 1) drawPiScreen(forceFullRedraw);
      forceFullRedraw = false;
    }
  }
#else
  if (now - lastFetch >= fetchInterval) {   // Ultra: single core, blocking fetch
    fetchCurrent();
    lastFetch = now;
    if (!clockMode) {
      if (cfg.mode == 0) drawPage(forceFullRedraw);
      else drawPiScreen(forceFullRedraw);
      forceFullRedraw = false;
    }
  }
#endif

  // Night window: dim and/or big clock, each independent.
  bool night = isNightNow();
  uint8_t targetB = (night && cfg.nightDim) ? cfg.nightBright : cfg.brightness;
  if (targetB != appliedBright) applyBrightness(targetB);

  // Night auto-clock: when the night window opens, default to the clock. But if
  // the user then picks a mode (menu/web -> applyMode/handleSave clear autoClock),
  // stay in that mode for the rest of this night. Each new night re-arms it.
  if (night && !prevNight && cfg.nightClock) autoClock = true;   // night just began
  if (!night) autoClock = false;                                 // daytime: never auto-clock
  prevNight = night;

  bool wantClock = (cfg.mode == 2) || autoClock;
  if (wantClock != clockMode) {           // mode just changed
    clockMode = wantClock;
    lastClockMin = -1;
    if (clockMode) drawClockScreen();
    else { renderCurrent(); lastPage = now; }
  }

  time_t t = time(nullptr);
  struct tm tm;
  bool haveTime = t > 100000;
  if (haveTime) localtime_r(&t, &tm);

  if (clockMode) {
    // full redraw on minute change; just the seconds ring the rest of the time
    if (haveTime && tm.tm_min != lastClockMin) {
      drawClockScreen(); lastClockMin = tm.tm_min; lastSec = tm.tm_sec;
    } else if (haveTime && tm.tm_sec != lastSec) {
      drawSecondsRing(tm.tm_sec); lastSec = tm.tm_sec;
    }
  } else if (cfg.mode == 0) {
    // market: page cycling + live header clock
    if (now - lastPage >= (uint32_t)cfg.pageSec * 1000UL) {
      page = (page + 1) % NUM_PAGES;
      drawPage(false, true);
      lastPage = now;
    }
    if (haveTime && tm.tm_min != lastSec) { drawFooter(); lastSec = tm.tm_min; }
  }
  // Pi monitor (mode 1): static screen, redrawn on the fetch tick only.

  delay(50);
}
