// Emoji-style weather icon (~22x20) mapped from an Open-Meteo WMO code.
void drawWeatherIcon(int x, int y, int code) {
  const uint16_t SUN   = tft.color565(255, 200, 0);
  const uint16_t CLOUD = tft.color565(205, 210, 222);
  const uint16_t RAIN  = tft.color565(70, 140, 255);
  const uint16_t UMB   = tft.color565(235, 70, 70);
  const uint16_t BOLT  = tft.color565(255, 210, 0);
  int cx = x + 10, cy = y + 9;

  int cat;  // 0 sun, 1 cloud, 2 rain(umbrella), 3 snow, 4 storm, 5 fog
  if (code <= 1) cat = 0;
  else if (code == 2 || code == 3) cat = 1;
  else if (code == 45 || code == 48) cat = 5;
  else if ((code >= 51 && code <= 67) || (code >= 80 && code <= 82)) cat = 2;
  else if ((code >= 71 && code <= 77) || code == 85 || code == 86) cat = 3;
  else if (code >= 95) cat = 4;
  else cat = 1;

  switch (cat) {
    case 0:  // sun
      tft.fillCircle(cx, cy, 5, SUN);
      for (int a = 0; a < 360; a += 45) {
        float r = a * 0.01745329;
        tft.drawLine(cx + cos(r) * 7, cy + sin(r) * 7,
                     cx + cos(r) * 10, cy + sin(r) * 10, SUN);
      }
      break;
    case 1:  // cloud
      drawCloudShape(cx, cy, CLOUD);
      break;
    case 2:  // rain -> umbrella
      tft.fillCircle(cx, cy - 1, 8, UMB);
      tft.fillRect(cx - 9, cy, 19, 10, COL_BG);  // keep only the dome
      tft.drawFastVLine(cx, cy - 1, 9, CLOUD);   // shaft
      tft.drawLine(cx, cy + 8, cx - 2, cy + 7, CLOUD);
      tft.fillCircle(cx + 6, cy + 7, 1, RAIN);   // a raindrop
      break;
    case 3:  // snow
      for (int a = 0; a < 180; a += 60) {
        float r = a * 0.01745329;
        tft.drawLine(cx - cos(r) * 7, cy - sin(r) * 7,
                     cx + cos(r) * 7, cy + sin(r) * 7, TFT_WHITE);
      }
      tft.fillCircle(cx, cy, 1, TFT_WHITE);
      break;
    case 4:  // thunderstorm
      drawCloudShape(cx, cy - 1, CLOUD);
      tft.drawLine(cx + 1, cy + 3, cx - 2, cy + 8, BOLT);
      tft.drawLine(cx - 2, cy + 8, cx + 1, cy + 8, BOLT);
      tft.drawLine(cx + 1, cy + 8, cx - 1, cy + 12, BOLT);
      break;
    default:  // fog
      for (int i = 0; i < 3; i++) tft.drawFastHLine(cx - 8, cy - 3 + i * 4, 17, CLOUD);
      break;
  }
}

