// Insert thousands separators, e.g. 65000.5 -> "65,000.50"
String withCommas(double v, uint8_t dec) {
  char buf[32];
  dtostrf(v, 0, dec, buf);
  String s(buf);
  int dot    = s.indexOf('.');
  int intEnd = (dot == -1) ? s.length() : dot;
  int start  = (s.length() > 0 && s[0] == '-') ? 1 : 0;
  String res;
  for (int i = 0; i < (int)s.length(); i++) {
    if (i > start && i < intEnd && ((intEnd - i) % 3 == 0)) res += ',';
    res += s[i];
  }
  return res;
}

// ---------------------------- data fetching ----------------------------
bool httpGetStream(const char* url, WiFiClientSecure& client, HTTPClient& https,
                   bool yahooHeaders) {
  client.setInsecure();  // skip cert validation (no root CA store on ESP8266)
  // NOTE: don't shrink the RX buffer here. CoinGecko/Yahoo sit behind CDNs that
  // usually don't support TLS max-fragment-length, so a small buffer breaks the
  // handshake. The default 16KB buffer is what makes HTTPS reliable on ESP8266.
  if (!https.begin(client, url)) { g_lastHttpCode = -999; return false; }
  // A descriptive User-Agent is REQUIRED: CoinGecko returns 403 without one.
  https.addHeader("User-Agent", "Glance/1.0 (ESP8266)");
  if (yahooHeaders) https.addHeader("Accept", "application/json");
  int code = https.GET();
  g_lastHttpCode = code;
  if (code != HTTP_CODE_OK) {
    Serial.printf("GET %s -> %d\n", url, code);
    https.end();
    return false;
  }
  return true;
}

// Bithumb spot price (Korean exchange, KRW = kimchi-premium-inclusive).
// closing_price = last trade, fluctate_rate_24H = 24h change %. Both are JSON strings.
void fetchBithumbOne(const char* sym, Ticker& t) {
  WiFiClientSecure client;
  HTTPClient https;
  String url = String("https://api.bithumb.com/public/ticker/") + sym + "_KRW";
  if (!httpGetStream(url.c_str(), client, https, false)) return;

  String payload = https.getString();  // getString() de-chunks
  https.end();
  JsonDocument doc;
  if (deserializeJson(doc, payload)) return;
  if (strcmp(doc["status"] | "", "0000") != 0) return;  // Bithumb OK status
  JsonObject d = doc["data"];
  if (d.isNull()) return;
  float price = atof(d["closing_price"]     | "0");
  float rate  = atof(d["fluctate_rate_24H"] | "0");
  if (price <= 0) return;
  t.price     = price;
  t.changePct = rate;
  t.valid     = true;
}


// One Yahoo Finance chart symbol -> one Ticker. sym is URL-encoded (^KS11 = %5EKS11).
// withSpark=true also captures the intraday close series into t.spark for a sparkline.
void fetchYahooOne(const char* sym, Ticker& t, bool withSpark = false) {
  WiFiClientSecure client;
  HTTPClient https;
  String url = String("https://query1.finance.yahoo.com/v8/finance/chart/") +
               sym + "?range=1d&interval=30m";
  if (!httpGetStream(url.c_str(), client, https, true)) return;

  // Filter down to the fields we need (meta + optionally the close series).
  JsonDocument filter;
  filter["chart"]["result"][0]["meta"]["regularMarketPrice"] = true;
  filter["chart"]["result"][0]["meta"]["chartPreviousClose"] = true;
  if (withSpark)
    filter["chart"]["result"][0]["indicators"]["quote"][0]["close"] = true;

  JsonDocument doc;
  DeserializationError err =
      deserializeJson(doc, https.getStream(), DeserializationOption::Filter(filter));
  https.end();
  if (err) { Serial.printf("yahoo json: %s\n", err.c_str()); return; }

  JsonObject meta = doc["chart"]["result"][0]["meta"];
  if (meta.isNull()) return;
  float p  = meta["regularMarketPrice"] | 0.0f;
  float pc = meta["chartPreviousClose"] | 0.0f;
  if (p <= 0 || pc <= 0) return;
  t.price     = p;
  t.changePct = (p - pc) / pc * 100.0f;
  t.valid     = true;

  if (withSpark) {
    JsonArray cl = doc["chart"]["result"][0]["indicators"]["quote"][0]["close"];
    float tmp[64];
    int tn = 0;
    for (JsonVariant v : cl)
      if (!v.isNull() && tn < 64) tmp[tn++] = v.as<float>();
    int start = (tn > SPARK_N) ? tn - SPARK_N : 0;  // keep the most recent points
    t.sparkN = 0;
    for (int i = start; i < tn; i++) t.spark[t.sparkN++] = tmp[i];
  }
}

void fetchWeather() {
  WiFiClientSecure client;
  HTTPClient https;
  String url = String("https://api.open-meteo.com/v1/forecast?latitude=") +
               String(LAT, 4) + "&longitude=" + String(LON, 4) +
               "&current=temperature_2m,weather_code";
  if (!httpGetStream(url.c_str(), client, https, false)) { g_dbgWx = g_lastHttpCode; return; }

  String payload = https.getString();  // getString() de-chunks; raw stream does not
  https.end();
  JsonDocument doc;
  DeserializationError err = deserializeJson(doc, payload);
  if (err) { g_dbgWx = -(200 + (int)err.code()); Serial.printf("weather json: %s\n", err.c_str()); return; }

  JsonVariant t = doc["current"]["temperature_2m"];
  if (t.isNull()) { g_dbgWx = -3; return; }
  g_tempC     = t.as<float>();
  g_wxCode    = doc["current"]["weather_code"] | -1;
  g_tempValid = true;
  g_dbgWx     = 200;
}

